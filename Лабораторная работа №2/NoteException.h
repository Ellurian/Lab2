#pragma once                                   // защита от повторного подключения этого файла (чтобы класс не определился дважды)
#include <exception>                           // подключаем стандартный базовый класс исключений std::exception
#include <string>                              // подключаем класс std::string для хранения текста ошибки

// Класс NoteException - наше собственное исключение.
// Мы "наследуем" его от std::exception (public-наследование: "NoteException ЯВЛЯЕТСЯ исключением").
class NoteException : public std::exception    // начало описания класса, двоеточие означает наследование
{
private:                                       // закрытая часть: снаружи класса её не видно
    std::string message;                       // текст, поясняющий, что именно пошло не так

public:                                        // открытая часть: эти функции можно вызывать снаружи
    NoteException();                           // конструктор без параметров (текст ошибки по умолчанию)
    NoteException(const std::string& text);    // конструктор с параметром (передаём свой текст ошибки)
    NoteException(const NoteException& other); // конструктор копирования (создаёт копию другого исключения)
    ~NoteException() override;                 // деструктор (вызывается при уничтожении объекта)

    const char* what() const noexcept override; // метод, возвращающий текст ошибки (переопределяет what() из std::exception)
};                                             // конец описания класса (после } в классе обязательна точка с запятой)
