#include "NoteException.h"                     // подключаем описание класса, реализацию которого пишем ниже
#include <iostream>                            // подключаем cout/endl для вывода сообщений на экран

// Конструктор без параметров: после двоеточия идёт "список инициализации" - задаём начальное значение поля message
NoteException::NoteException() : message("Неизвестная ошибка")
{
    // выводим информацию о вызове конструктора (так требует задание)
    std::cout << "  [Исключение] Вызван конструктор без параметров: \"" << message << "\"" << std::endl;
}                                              // конец конструктора

// Конструктор с параметром: сохраняем переданный текст в поле message
NoteException::NoteException(const std::string& text) : message(text)
{
    // сообщаем пользователю, какой конструктор вызван
    std::cout << "  [Исключение] Вызван конструктор с параметром: \"" << message << "\"" << std::endl;
}                                              // конец конструктора

// Конструктор копирования: создаёт новый объект как копию other
NoteException::NoteException(const NoteException& other) : std::exception(other), message(other.message)
{
    // сообщаем, что вызван конструктор копирования (C++ может копировать исключение при throw/catch)
    std::cout << "  [Исключение] Вызван конструктор копирования: \"" << message << "\"" << std::endl;
}                                              // конец конструктора

// Деструктор: вызывается автоматически, когда объект перестаёт существовать
NoteException::~NoteException()
{
    // сообщаем, что исключение уничтожается
    std::cout << "  [Исключение] Вызван деструктор: \"" << message << "\"" << std::endl;
}                                              // конец деструктора

// Метод what() возвращает текст ошибки в виде обычной C-строки
const char* NoteException::what() const noexcept
{
    return message.c_str();                    // c_str() превращает std::string в const char*
}                                              // конец метода
