#include <iostream>                            // cout / endl
#include <fstream>                             // ifstream - файловый поток (чтение из файла)
#include <sstream>                             // stringstream - строковый поток (работа со строкой как с потоком)
#include <cctype>                              // isspace - проверка "пробельный ли символ"

// Проверяет, начинается ли строка s с тире в позиции pos.
// Тире бывает разным: дефис '-', короткое '–' (U+2013) и длинное '—' (U+2014).
// В кодировке UTF-8 короткое и длинное тире занимают по 3 байта, поэтому записаны байтами.
static bool startsWithDash(const std::string& s, size_t pos)
{
    if (s.compare(pos, 1, "-") == 0)           // обычный дефис (1 байт)
    {
        return true;                           // это тире
    }                                          // конец if
    if (s.compare(pos, 3, "\xE2\x80\x94") == 0) // длинное тире "—" (3 байта UTF-8)
    {
        return true;                           // это тире
    }                                          // конец if
    if (s.compare(pos, 3, "\xE2\x80\x93") == 0) // короткое тире "–" (3 байта UTF-8)
    {
        return true;                           // это тире
    }                                          // конец if
    return false;                              // ни одно из тире не подошло
}                                              // конец функции

// Обрабатывает одно предложение: если оно начинается с тире - печатает его.
// Возвращает true, если предложение было напечатано.
static bool processSentence(const std::string& sentence)
{
    size_t pos = 0;                            // позиция первого непробельного символа
    while (pos < sentence.size() && std::isspace(static_cast<unsigned char>(sentence[pos]))) // пока символ пробельный (пробел, \n, \t...)
    {
        ++pos;                                 // пропускаем его
    }                                          // конец while
    if (pos == sentence.size())                // если в предложении одни пробелы
    {
        return false;                          // печатать нечего
    }                                          // конец if
    if (startsWithDash(sentence, pos))         // первый непробельный символ - тире?
    {
        std::cout << "  " << sentence.substr(pos) << std::endl; // печатаем предложение без ведущих пробелов
        return true;                           // сообщаем, что нашли
    }                                          // конец if
    return false;                              // предложение не с тире - пропускаем
}                                              // конец функции

void printDashSentences(const std::string& fileName)
{
    std::ifstream file(fileName);              // открываем файл для чтения (файловый поток)
    if (!file.is_open())                       // если файл не открылся (нет такого файла, неверный путь)
    {
        throw NoteException("Не удалось открыть файл: " + fileName); // ошибка с пояснением
    }                                          // конец if

    std::stringstream buffer;                  // строковый поток: "виртуальный файл" в памяти
    buffer << file.rdbuf();                    // переливаем всё содержимое файла в строковый поток одним действием
    file.close();                              // файл больше не нужен - закрываем

    std::string sentence;                      // сюда по символам набираем текущее предложение
    char ch;                                   // текущий прочитанный символ
    int found = 0;                             // сколько предложений с тире нашли

    std::cout << "Предложения, начинающиеся с тире:" << std::endl; // заголовок результата

    while (buffer.get(ch))                     // читаем символы по одному, пока они не закончатся
    {
        sentence += ch;                        // добавляем символ к текущему предложению
        if (ch == '.' || ch == '!' || ch == '?') // знак конца предложения
        {
            // Многоточие и сочетания вроде "?!" - это ОДИН конец предложения, поэтому дочитываем подряд идущие знаки
            while (buffer.peek() == '.' || buffer.peek() == '!' || buffer.peek() == '?') // peek() подсматривает следующий символ, не забирая его
            {
                buffer.get(ch);                // забираем этот знак
                sentence += ch;                // и добавляем к предложению
            }                                  // конец while
            if (processSentence(sentence))     // обрабатываем готовое предложение
            {
                ++found;                       // если оно с тире - увеличиваем счётчик
            }                                  // конец if
            sentence.clear();                  // очищаем накопитель для следующего предложения
        }                                      // конец if
    }                                          // конец while

    if (!sentence.empty() && processSentence(sentence)) // хвост текста без точки в конце тоже считается предложением
    {
        ++found;                               // учитываем его
    }                                          // конец if

    if (found == 0)                            // если ничего не нашли
    {
        std::cout << "  Предложений, начинающихся с тире, в файле нет." << std::endl; // сообщение по смыслу задания
    }                                          // конец if
}                                              // конец функции
